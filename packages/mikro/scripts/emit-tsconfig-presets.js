#!/usr/bin/env node
/**
 * Emit the tsconfig presets in tsconfig/ (default.json, plus one
 * <chip>-generic.json per chip) from the feature table in
 * @mikrojs/native/runtime/modules.json and the chip list in
 * @mikrojs/firmware/chips.json.
 *
 * Feature-gated package subpaths (mikro/wifi, mikro/ble, ...) resolve only
 * under their mikro:<feature> condition. default.json, exported as
 * mikro/tsconfig, grants every feature; a chip or board preset grants what
 * that target supports, so it only ever narrows.
 *
 * Usage: node emit-tsconfig-presets.js [out-dir]
 */
import {mkdirSync, readFileSync, writeFileSync} from 'node:fs'
import path from 'node:path'
import {fileURLToPath} from 'node:url'

const modulesJson = JSON.parse(
  readFileSync(new URL(import.meta.resolve('@mikrojs/native/runtime/modules.json')), 'utf8'),
)
const chipsJson = JSON.parse(
  readFileSync(
    new URL('./chips.json', import.meta.resolve('@mikrojs/firmware/package.json')),
    'utf8',
  ),
)

const allFeatures = [...new Set(modulesJson.modules.map((m) => m.feature).filter(Boolean))].sort()

// Every current chip supports every feature; when a chip without one of them
// is added, derive its feature subset here.
const chipFeatures = new Map(chipsJson.chips.map((chip) => [chip, allFeatures]))

// Hand-assembled so the output is already in oxfmt's JSON style.
function preset(features) {
  const conditions = features.map((feature) => `"mikro:${feature}"`).join(', ')
  return `{
  "$comment": "Generated by scripts/emit-tsconfig-presets.js from @mikrojs/native/runtime/modules.json and @mikrojs/firmware/chips.json; do not edit by hand",
  "extends": "../tsconfig.base.json",
  "compilerOptions": {
    "customConditions": [${conditions}]
  }
}
`
}

const outDir = process.argv[2] ?? fileURLToPath(new URL('../tsconfig/', import.meta.url))
mkdirSync(outDir, {recursive: true})
for (const [chip, features] of chipFeatures) {
  writeFileSync(path.join(outDir, `${chip}-generic.json`), preset(features))
}
writeFileSync(path.join(outDir, 'default.json'), preset(allFeatures))
